import { test, expect } from '@playwright/test'

test('Alex recommendations save public projects and open the shortlist on a small screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const posts = []
  page.on('request', request => { if (request.method() === 'POST') posts.push(request.url()) })
  await page.goto('/projects/zalio-crm')
  await page.getByRole('button', { name: 'Open Alex, AI Portfolio Assistant' }).click()
  const panel = page.getByRole('dialog', { name: 'Alex', exact: true })
  await panel.getByRole('button', { name: 'Find projects', exact: true }).click()
  await panel.getByRole('textbox', { name: 'Describe your project' }).fill('Private clinic needs a CRM with automated follow-ups')
  await panel.getByRole('button', { name: 'Send question' }).click()
  const card = panel.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Zalio CRM', exact: true }) })
  await card.getByRole('button', { name: 'Add Zalio CRM to shortlist', exact: true }).click()
  await expect(card.getByRole('button', { name: 'Remove Zalio CRM from shortlist', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await card.getByRole('link', { name: 'View shortlist', exact: true }).click()
  await expect(panel).toHaveCount(0)
  await expect(page).toHaveURL(/\/projects#project-shortlist$/)
  const comparison = page.getByRole('region', { name: 'Your project shortlist' })
  await expect(comparison.getByRole('heading', { name: 'Zalio CRM', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Your project shortlist', exact: true })).toBeInViewport()
  const storage = await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }))
  expect(storage.session['portfolio-project-shortlist']).toBe('["zalio-crm"]')
  expect(JSON.stringify(storage)).not.toContain('Private clinic')
  expect(posts).toEqual([])
})

test('Alex uses the existing shortlist limit and can remove its saved recommendation', async ({ page }) => {
  await page.goto('/projects?compare=oneride,alex-hasti,bboy#project-shortlist')
  await page.getByRole('button', { name: 'Open Alex, AI Portfolio Assistant' }).click()
  const panel = page.getByRole('dialog', { name: 'Alex', exact: true })
  await panel.getByRole('button', { name: 'Find projects', exact: true }).click()
  await panel.getByRole('textbox', { name: 'Describe your project' }).fill('Zalio CRM')
  await panel.getByRole('button', { name: 'Send question' }).click()
  const card = panel.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Zalio CRM', exact: true }) })
  await card.getByRole('button', { name: 'Add Zalio CRM to shortlist', exact: true }).click()
  await expect(card.getByRole('status')).toContainText('up to 3')
  await expect(card.getByRole('button', { name: 'Add Zalio CRM to shortlist', exact: true })).toHaveAttribute('aria-pressed', 'false')
  const saved = panel.getByRole('button', { name: 'Remove Alex / Hasti from shortlist', exact: true })
  // A fresh recommendation for the saved public project uses the same store.
  await panel.getByRole('textbox', { name: 'Describe your project' }).fill('Alex / Hasti')
  await panel.getByRole('button', { name: 'Send question' }).click()
  await saved.last().click()
  await card.getByRole('button', { name: 'Add Zalio CRM to shortlist', exact: true }).click()
  await expect(card.getByRole('button', { name: 'Remove Zalio CRM from shortlist', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await card.getByRole('button', { name: 'Remove Zalio CRM from shortlist', exact: true }).click()
  await expect(card.getByRole('button', { name: 'Add Zalio CRM to shortlist', exact: true })).toHaveAttribute('aria-pressed', 'false')
})
