import { test, expect } from '@playwright/test'

test('cloud and delivery categories connect capabilities to honest project evidence', async ({ page }) => {
  await page.goto('/#skills')
  const skills = page.locator('#skills')
  await skills.getByRole('tab', { name: /AWS & cloud/ }).click()
  const panel = skills.getByRole('tabpanel')
  await expect(panel).toContainText('AWS Lambda')
  await expect(panel).toContainText(/private/i)
  await expect(panel.getByRole('link', { name: /fintech/i })).toHaveAttribute('href', '/projects/fintech-lending')
  await skills.getByRole('tab', { name: /DevOps & delivery/ }).click()
  await expect(panel).toContainText('Docker Compose')
  await expect(panel).toContainText('GitHub Actions')
  await expect(panel.getByRole('link', { name: /OMJI/i })).toHaveAttribute('href', '/projects/omji-billing')
})

test('skills search finds a technology, announces empty results, and resets with focus', async ({ page }) => {
  await page.goto('/#skills')
  const skills = page.locator('#skills')
  const search = skills.getByRole('searchbox', { name: 'Search tools and practices' })
  await search.fill('  pLaYwRiGhT  ')
  await expect(skills.getByRole('tabpanel')).toContainText('Playwright')
  await expect(skills.getByRole('status')).toContainText('1 capability')
  await expect(skills.getByRole('tab')).toHaveCount(1)
  await search.fill('no-such-integration-987')
  await expect(skills.getByRole('status')).toContainText('0 capabilities')
  await expect(skills.getByText('No tools match this search.')).toBeVisible()
  await expect(skills.getByRole('tabpanel')).toHaveCount(0)
  await skills.getByRole('button', { name: 'Clear skills search' }).click()
  await expect(search).toHaveValue('')
  await expect(search).toBeFocused()
  await expect(skills.getByRole('tab', { name: /AI & automation/ })).toHaveAttribute('aria-selected', 'true')
})

test('capability tabs keep a single keyboard stop and wrap across the available groups', async ({ page }) => {
  await page.goto('/#skills')
  const skills = page.locator('#skills')
  const first = skills.getByRole('tab', { name: /AI & automation/ })
  await first.focus()
  await page.keyboard.press('ArrowRight')
  const backend = skills.getByRole('tab', { name: /Backend & APIs/ })
  await expect(backend).toBeFocused()
  await expect(backend).toHaveAttribute('aria-selected', 'true')
  await expect(first).toHaveAttribute('tabindex', '-1')
  await page.keyboard.press('End')
  await expect(skills.getByRole('tab', { name: /Systems & integrations/ })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(first).toBeFocused()
  await expect(skills.locator('[role="tab"][tabindex="0"]')).toHaveCount(1)
})

for (const theme of ['light', 'dark']) {
  test(`skills search and evidence fit a 320px screen in ${theme} mode`, async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 740 })
    await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
    await page.goto('/#skills')
    const skills = page.locator('#skills')
    const search = skills.getByRole('searchbox', { name: 'Search tools and practices' })
    await search.fill('AWS Lambda')
    await expect(skills.getByRole('tabpanel')).toContainText('AWS Lambda')
    await expect(skills.getByRole('link', { name: /fintech/i })).toBeVisible()
    await expect.poll(() => skills.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    const control = await search.boundingBox()
    expect(control.width).toBeGreaterThan(200)
    expect(control.height).toBeGreaterThanOrEqual(44)
  })
}
