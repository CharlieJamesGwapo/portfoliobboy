export function filterAutomationWorkflows({ platform = 'All', query = '' } = {}) {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean)
  return automationWorkflows.filter((workflow) => {
    if (platform !== 'All' && workflow.platform !== platform) return false
    const searchable = [workflow.title, workflow.summary, workflow.useCase, workflow.trigger, workflow.outcome,
      workflow.platform, workflow.implementation, workflow.safeguards, ...workflow.steps, ...workflow.tools]
      .join(' ').toLocaleLowerCase()
    return terms.every((term) => searchable.includes(term))
  })
}
